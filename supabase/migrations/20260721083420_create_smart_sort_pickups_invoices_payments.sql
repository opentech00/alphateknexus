-- ============ payments ============
CREATE TABLE IF NOT EXISTS smart_sort_payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  invoice_id uuid NOT NULL REFERENCES smart_sort_invoices(id) ON DELETE CASCADE,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  amount_sle integer NOT NULL,
  method text NOT NULL CHECK (method IN ('cash','bank_transfer','africell_money','orange_money','qmoney','other')),
  reference text,
  status text NOT NULL DEFAULT 'confirmed' CHECK (status IN ('pending','confirmed','failed')),
  recorded_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz DEFAULT now()
);

